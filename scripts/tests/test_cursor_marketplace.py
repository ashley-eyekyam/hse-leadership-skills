"""test_cursor_marketplace.py — Cursor Team Marketplace invariants + drift gate.

Locks `.cursor-plugin/marketplace.json` generated by `gen_marketplace.py` for
Cursor Team Marketplace Import-from-Repo. Asserts:

  * root name / owner / metadata present; no Claude-only fields
  * exactly the 18 Claude-parity plugin names, unique
  * every skills[] path exists, contains SKILL.md, is relative, no `..`
  * hse-all excludes hse-skill-forge and includes using-hse-skills
  * hse-systems is only ./skills/hse-skill-forge
  * Cursor membership equals Claude membership for each bundle name
  * on-disk == generated (drift gate, same as Claude)

Pure deterministic Python against the committed repo tree + tmp fixtures:
no network, no model, no key.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import pytest

# scripts/tests/<this> -> repo/scripts on sys.path for `gen_marketplace`.
SCRIPTS = Path(__file__).resolve().parents[1]
REPO = SCRIPTS.parent
if str(SCRIPTS) not in sys.path:
    sys.path.insert(0, str(SCRIPTS))

import gen_marketplace  # noqa: E402

CURSOR = REPO / ".cursor-plugin" / "marketplace.json"
CLAUDE = REPO / ".claude-plugin" / "marketplace.json"
CODEX = REPO / ".codex-plugin" / "plugin.json"

_EXPECTED_NAMES = {
    "hse-all",
    "hse-aviation",
    "hse-chemicals",
    "hse-construction",
    "hse-core",
    "hse-healthcare",
    "hse-india",
    "hse-leadership",
    "hse-logistics-transport",
    "hse-manufacturing",
    "hse-marine-offshore",
    "hse-mining",
    "hse-operations",
    "hse-process",
    "hse-rail",
    "hse-renewables",
    "hse-systems",
    "hse-utilities-power",
}

_FM = """---
name: {name}
description: A fixture skill.
license: Apache-2.0
metadata:
  plugin: {plugin}
---

# body
"""


def _write_skill(repo: Path, name: str, plugin: str) -> None:
    d = repo / "skills" / name
    d.mkdir(parents=True)
    (d / "SKILL.md").write_text(_FM.format(name=name, plugin=plugin), encoding="utf-8")


def _skill_names(skills: list) -> list:
    return [s.rsplit("/", 1)[-1] for s in skills]


@pytest.fixture(scope="module")
def cursor_manifest() -> dict:
    assert CURSOR.is_file(), "missing .cursor-plugin/marketplace.json — run gen_marketplace.py --write"
    payload = json.loads(CURSOR.read_text(encoding="utf-8"))
    assert isinstance(payload, dict)
    return payload


@pytest.fixture(scope="module")
def claude_manifest() -> dict:
    return json.loads(CLAUDE.read_text(encoding="utf-8"))


@pytest.fixture(scope="module")
def codex_version() -> str:
    return json.loads(CODEX.read_text(encoding="utf-8"))["version"]


def test_cursor_root_schema(cursor_manifest, codex_version):
    assert cursor_manifest["name"] == "hse-leadership-skills"
    assert cursor_manifest["owner"] == {
        "name": "Eyekyam",
        "email": "ashley@eyekyam.com",
    }
    meta = cursor_manifest["metadata"]
    assert meta["version"] == codex_version
    assert meta["description"].strip()
    # Claude-only fields must never appear on the Cursor marketplace root.
    for banned in ("$schema", "_comment", "strict"):
        assert banned not in cursor_manifest


def test_exactly_eighteen_unique_plugins(cursor_manifest):
    names = [p["name"] for p in cursor_manifest["plugins"]]
    assert len(names) == 18
    assert set(names) == _EXPECTED_NAMES
    assert len(names) == len(set(names))


def test_plugin_entry_shape(cursor_manifest, codex_version):
    logo = REPO / "docs" / "assets" / "logo.svg"
    for entry in cursor_manifest["plugins"]:
        assert entry["source"] == "."
        assert entry["version"] == codex_version
        assert entry["author"] == {
            "name": "Eyekyam Risk Resolutions Pvt. Ltd.",
            "email": "ashley@eyekyam.com",
        }
        assert entry["license"] == "Apache-2.0"
        assert entry["homepage"] == "https://github.com/ashley-eyekyam/hse-leadership-skills"
        assert entry["repository"] == entry["homepage"]
        assert entry["category"] == "Productivity"
        assert entry["description"].strip()
        assert isinstance(entry["keywords"], list) and entry["keywords"]
        assert "strict" not in entry
        assert "$schema" not in entry
        if logo.is_file():
            assert entry["logo"] == "docs/assets/logo.svg"
        skills = entry["skills"]
        assert isinstance(skills, list) and skills
        assert skills == sorted(skills), "skill paths must be deterministically sorted"
        for path in skills:
            assert path.startswith("./skills/"), path
            assert ".." not in path
            assert not path.startswith("/")
            skill_dir = REPO / path[2:]  # strip leading ./
            assert skill_dir.is_dir(), f"missing skill dir {path}"
            assert (skill_dir / "SKILL.md").is_file(), f"missing SKILL.md under {path}"


def test_hse_all_and_systems_membership(cursor_manifest):
    by_name = {p["name"]: p["skills"] for p in cursor_manifest["plugins"]}
    all_skills = _skill_names(by_name["hse-all"])
    assert len(all_skills) == 93
    assert "using-hse-skills" in all_skills
    assert "hse-skill-forge" not in all_skills
    assert by_name["hse-systems"] == ["./skills/hse-skill-forge"]


def test_cursor_membership_equals_claude(cursor_manifest, claude_manifest):
    cursor_by = {p["name"]: p["skills"] for p in cursor_manifest["plugins"]}
    claude_by = {p["name"]: p["skills"] for p in claude_manifest["plugins"]}
    assert set(cursor_by) == set(claude_by)
    for name in sorted(claude_by):
        assert cursor_by[name] == claude_by[name], (
            f"Cursor membership for {name} must equal Claude membership"
        )


def test_on_disk_equals_generated():
    """Drift gate: committed Cursor marketplace == fresh build_cursor_manifest."""
    generated = gen_marketplace._serialize(gen_marketplace.build_cursor_manifest(REPO))
    on_disk = CURSOR.read_text(encoding="utf-8")
    assert generated == on_disk, (
        ".cursor-plugin/marketplace.json drifted; run `gen_marketplace.py --write`"
    )


def test_check_covers_cursor_drift(tmp_path):
    """Corrupting only the Cursor marketplace makes --check fail (CI gate)."""
    _write_skill(tmp_path, "risk-assessment", "hse-core")
    _write_skill(tmp_path, "using-hse-skills", "hse-core")
    _write_skill(tmp_path, "hse-skill-forge", "hse-systems")
    # Seed Codex version so Cursor entries get a real semver.
    codex = tmp_path / ".codex-plugin"
    codex.mkdir()
    (codex / "plugin.json").write_text(
        json.dumps({"name": "hse-leadership-skills", "version": "1.3.0"}),
        encoding="utf-8",
    )
    assert gen_marketplace.main(["--write", "--repo", str(tmp_path)]) == 0
    cursor_path = tmp_path / ".cursor-plugin" / "marketplace.json"
    good = cursor_path.read_text(encoding="utf-8")
    cursor_path.write_text(good.replace("hse-core", "hse-WRONG", 1), encoding="utf-8")
    rc = gen_marketplace.main(["--check", "--repo", str(tmp_path)])
    assert rc != 0, "Cursor marketplace drift must fail --check"


def test_build_cursor_strips_claude_only_fields(tmp_path):
    _write_skill(tmp_path, "risk-assessment", "hse-core")
    cursor = gen_marketplace.build_cursor_manifest(tmp_path)
    assert "$schema" not in cursor
    assert "_comment" not in cursor
    for entry in cursor["plugins"]:
        assert "strict" not in entry
        assert entry["source"] == "."
